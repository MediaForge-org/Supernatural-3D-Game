	struct FRouteSpec
	{
		const TCHAR* Name;
		FVector Start;           // XY of the teleport point; Z is the standing height on the ground (StandZ)
		TArray<FVector2D> Points;
		float FinalZ;            // expected capsule centre height at the end
		float FinalZTolerance;
	};

	/** Waypoints from the layout (see header comment). `Floor` is the walking-surface height of the upper floor. */
	TArray<FRouteSpec> BuildRoutes()
	{
		TArray<FRouteSpec> Routes;
		auto Entrance = [&Routes](const TCHAR* Name, FVector2D Out, FVector2D Front, FVector2D Inside)
		{
			Routes.Add({Name, FVector(Out.X, Out.Y, StandZ), {Front, Inside}, StandZ, 25.f});
		};
		Entrance(TEXT("Cottage1 entrance"), {-9800, -5440}, {-9550, -5440}, {-9290, -5440});
		Entrance(TEXT("House1 entrance"), {-9800, 8250}, {-9550, 8250}, {-9290, 8250});
		Entrance(TEXT("Cottage2 entrance"), {-9800, 12340}, {-9550, 12340}, {-9290, 12340});
		Entrance(TEXT("StorageHall entrance"), {-9700, -12700}, {-9450, -12700}, {-9190, -12700});
		Entrance(TEXT("Workshop entrance"), {6300, -12200}, {6550, -12200}, {6810, -12200});
		Entrance(TEXT("Garage entrance"), {10900, -12520}, {11150, -12520}, {11410, -12520});
		Entrance(TEXT("CourtHouse entrance"), {4900, 11020}, {5150, 11020}, {5410, 11020});
		Entrance(TEXT("Office1 entrance"), {13800, 3500}, {13550, 3500}, {13290, 3500});
		Entrance(TEXT("Cottage3 entrance"), {3700, 11160}, {3450, 11160}, {3190, 11160});
		// Office corridor: through the east door, west along the corridor to its far end.
		Routes.Add({TEXT("Office1 corridor"), FVector(13800, 3500, StandZ), {{13550, 3500}, {13290, 3500}, {12500, 3500}, {12000, 3500}}, StandZ, 25.f});
		// Two-storey houses: door, hall, up the stairs (stair feet/tops from the generated step boxes), landing.
		Routes.Add({TEXT("House1 hall to upper landing"), FVector(-9800, 8250, StandZ),
			{{-9550, 8250}, {-9330, 8250}, {-9330, 8440}, {-9330, 8886}, {-9330, 9000}}, 300.f + StandZ, 30.f});
		Routes.Add({TEXT("CourtHouse hall to upper landing"), FVector(4900, 11020, StandZ),
			{{5150, 11020}, {5370, 11020}, {5370, 11190}, {5370, 11686}, {5370, 11800}}, 320.f + StandZ, 30.f});
		return Routes;
	}

