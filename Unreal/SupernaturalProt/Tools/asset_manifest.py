"""READ-ONLY asset manifest (NightBuild06): one row per file under Content/, with size, origin, licence status, need, recovery and git status.

Usage (plain Python 3, no Unreal):
    python asset_manifest.py [--deps Saved/SpnAssets/asset_dependencies.json] [--out-csv FILE] [--out-summary FILE]
Run from anywhere; paths are relative to the Unreal project. `asset_dependency_report.py` (Unreal commandlet) writes the deps file; without
it the "needed_by" column stays empty.

Origin and licence come from path rules (ORIGIN_RULES below) that mirror Docs/Development/Fab-Asset-Sources.md and the character reports
0016 / 0017. They say what is *documented*, not what was verified on a licence page.
"""

import argparse
import collections
import csv
import json
import os
import subprocess
import sys

PROJECT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT = os.path.join(PROJECT, "Content")

# (path prefix under Content/, origin, licence status, recovery). First match wins: put more specific prefixes first.
ORIGIN_RULES = [
    ("Fab/", "third party: Fab / Quixel Megascans (imported by the developer 2026-11-12)",
     "Fab Standard License per Quixel announcement; licence page not checked by Claude",
     "re-import from the developer's Fab library (Docs/Development/Fab-Asset-Sources.md); must not go into a public repository"),
    ("Megaplant_Library/", "third party: Quixel Megaplants via Fab (imported by the developer 2026-11-12)",
     "Fab Standard License per Quixel announcement; licence page not checked by Claude",
     "re-import from the developer's Fab library (Fab-Asset-Sources.md); must not go into a public repository"),
    ("SpnWorld/FabDerived/", "own derivative of Fab content (Nanite copies of Megascans ferns)",
     "derived from Fab Standard License content: same restrictions as the source",
     "regenerate with Tools/spn_world_build.ps1 once the Fab sources exist"),
    ("SpnWorld/Data/", "own data (world generator output, JSON)", "own work", "versioned in git"),
    ("SpnWorld/", "own, generated by the world generator (Tools/spn_world, SpnWorldTool)",
     "own work; placed instances reference Fab / Megaplant assets",
     "regenerate with Tools/spn_world_build.ps1 -Phase B..H (not byte-identical; needs the Fab sources for the full look)"),
    ("SpnTest/", "own, generated by the test-map scripts (Tools/create_spn_*.py)", "own work",
     "versioned (tracked rows) or regenerate with the create_spn_*_test_map.py scripts (not byte-identical)"),
    ("SpnCharacterPrep/", "generated locally from MetaHuman (engine plugin) by Tools/character_*_setup.py",
     "MetaHuman licence (Epic): use with Unreal Engine; not cleared for a public repository",
     "regenerate with Tools/character_mh_test_setup.py / character_mh_male_setup.py (the male body needs Characters/ProtagonistV1)"),
    ("Characters/ProtagonistV1/", "MetaHuman Creator asset made by hand in the editor (2026-10-31)",
     "MetaHuman licence (Epic); not cleared for a public repository",
     "NOT regenerable without manual work: backup only"),
    ("Characters/Mannequins/", "Unreal Engine template content (Third Person template)", "UE EULA template content", "versioned in git (LFS)"),
    ("ThirdPerson/", "Unreal Engine template content", "UE EULA template content", "versioned in git (LFS)"),
    ("LevelPrototyping/", "Unreal Engine template content", "UE EULA template content", "versioned in git (LFS)"),
    ("Variant_", "Unreal Engine template content", "UE EULA template content", "versioned in git (LFS)"),
    ("Input/", "Unreal Engine template content (input actions)", "UE EULA template content", "versioned in git (LFS)"),
    ("__ExternalActors__/", "one-file-per-actor data of a map (origin = that map)", "as the owning map", "as the owning map"),
    ("__ExternalObjects__/", "one-file-per-actor data of a map (origin = that map)", "as the owning map", "as the owning map"),
    ("", "unclassified", "unknown", "unknown"),
]


def classify(rel):
    for prefix, origin, licence, recovery in ORIGIN_RULES:
        if rel.startswith(prefix):
            return origin, licence, recovery
    return ORIGIN_RULES[-1][1:]


def git_tracked():
    out = subprocess.run(["git", "ls-files", "-z", "Content"], cwd=PROJECT, capture_output=True, check=True).stdout
    return {p.decode("utf-8") for p in out.split(b"\0") if p}


def git_ignored(paths):
    if not paths:
        return set()
    proc = subprocess.run(["git", "check-ignore", "-z", "--stdin"], cwd=PROJECT, input=b"\0".join(p.encode("utf-8") for p in paths),
                          capture_output=True)
    return {p.decode("utf-8") for p in proc.stdout.split(b"\0") if p}


def needed_by(deps_file):
    """Content/<file> -> sorted list of roots (maps / config assets) that depend on it."""
    if not deps_file or not os.path.isfile(deps_file):
        return {}
    report = json.load(open(deps_file, encoding="utf-8"))
    need = collections.defaultdict(set)
    for root, entry in report.items():
        for info in entry.get("packages", {}).values():
            need[info["file"]].add(root.rsplit("/", 1)[-1])
    return {k: sorted(v) for k, v in need.items()}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--deps", default=os.path.join(PROJECT, "Saved", "SpnAssets", "asset_dependencies.json"))
    ap.add_argument("--out-csv", default=os.path.join(PROJECT, "Saved", "SpnAssets", "asset_manifest.csv"))
    ap.add_argument("--out-summary", default=os.path.join(PROJECT, "Saved", "SpnAssets", "asset_manifest_summary.json"))
    args = ap.parse_args(argv)

    files = []
    for dirpath, _, names in os.walk(CONTENT):
        for name in names:
            full = os.path.join(dirpath, name)
            files.append(("Content/" + os.path.relpath(full, CONTENT).replace(os.sep, "/"), os.path.getsize(full)))
    files.sort()
    tracked = git_tracked()
    ignored = git_ignored([f for f, _ in files if f not in tracked])
    need = needed_by(args.deps)

    summary = collections.OrderedDict()
    os.makedirs(os.path.dirname(os.path.abspath(args.out_csv)), exist_ok=True)
    with open(args.out_csv, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["path", "bytes", "origin", "licence_status", "needed_by", "recovery", "git_status"])
        for rel, size in files:
            inner = rel[len("Content/"):]
            origin, licence, recovery = classify(inner)
            status = "tracked" if rel in tracked else "ignored (local only)" if rel in ignored else "untracked"
            roots = need.get(rel, [])
            w.writerow([rel, size, origin, licence, ";".join(roots), recovery, status])
            group = inner.split("/")[0] if not inner.startswith("Variant_") else "Variant_*"
            if inner.startswith("SpnWorld/FabDerived/"):
                group = "SpnWorld/FabDerived"
            g = summary.setdefault(group, {"files": 0, "bytes": 0, "tracked_files": 0, "local_only_files": 0, "local_only_bytes": 0,
                                           "needed_files": 0, "origin": origin})
            g["files"] += 1
            g["bytes"] += size
            if status == "tracked":
                g["tracked_files"] += 1
            else:
                g["local_only_files"] += 1
                g["local_only_bytes"] += size
            if roots:
                g["needed_files"] += 1
    with open(args.out_summary, "w", encoding="utf-8") as fh:
        json.dump(summary, fh, indent=1)
    for group, g in summary.items():
        print("%-22s files %5d  %8.1f MB  tracked %4d  local-only %4d (%7.1f MB)  needed %4d" % (
            group, g["files"], g["bytes"] / 1e6, g["tracked_files"], g["local_only_files"], g["local_only_bytes"] / 1e6, g["needed_files"]))
    print("rows: %d -> %s" % (len(files), args.out_csv))
    return 0


if __name__ == "__main__":
    sys.exit(main())
