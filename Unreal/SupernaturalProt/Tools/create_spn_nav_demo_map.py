"""Creates the PLACEHOLDER demo map /Game/SpnTest/Lvl_SpnNavDemo (NightBuild03, map & navigation tech demo).

The level holds only: sun, sky atmosphere, sky light, fog, one Player Start and one ASpnNavDemo actor. The actor installs the Core's SYNTHETIC test
region into USpnMapSubsystem and builds its 3D version at BeginPlay (ground, water, roads, bridges, tunnel, buildings, trees), so the map screen, the
minimap and the world show the same data. The ground is generated by the actor; the level contains no geometry of its own.

The Player Start stands on the west street of the synthetic region (map 500 m east, 0 m north) in the DEMO coordinate adapter
(ESpnWorldAxes::EastSouthUp, origin 0): Unreal X = 50,000 cm, Y = 0. The adapter is a demo choice, not a global decision and not RC-01.

Run headless from the repository root (Windows):
    UnrealEditor-Cmd.exe Unreal/SupernaturalProt/SupernaturalProt.uproject -run=pythonscript
        -script="<abs path>/create_spn_nav_demo_map.py" -unattended -nullrhi
An existing map is kept unless "--force" follows the script path inside -script="...".
"""

import os
import sys

import unreal

MAP_PATH = "/Game/SpnTest/Lvl_SpnNavDemo"
DEMO_CLASS_PATH = "/Script/SupernaturalProt.SpnNavDemo"
PLAYER_START_LOCATION = unreal.Vector(50000.0, 0.0, 100.0)  # map (500, 0) m on the west street, facing east (+X)


def fail(message):
    unreal.log_error("SpnNavDemoMap: " + message)
    raise SystemExit(1)


def spawn(actor_class, location, yaw=0.0, pitch=0.0, label=None):
    actors = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
    actor = actors.spawn_actor_from_class(actor_class, location, unreal.Rotator(roll=0.0, pitch=pitch, yaw=yaw))
    if actor is None:
        fail("could not spawn " + str(actor_class))
    if label:
        actor.set_actor_label(label)
    return actor


def build_lighting():
    sun = spawn(unreal.DirectionalLight, unreal.Vector(0.0, 0.0, 500.0), yaw=35.0, pitch=-38.0, label="SPN_Sun")
    component = sun.get_component_by_class(unreal.DirectionalLightComponent)
    component.set_mobility(unreal.ComponentMobility.MOVABLE)
    component.set_editor_property("atmosphere_sun_light", True)
    atmosphere = spawn(unreal.SkyAtmosphere, unreal.Vector(0.0, 0.0, 0.0), label="SPN_SkyAtmosphere")
    try:
        atmosphere.get_component_by_class(unreal.SkyAtmosphereComponent).set_editor_property("aerial_pespective_view_distance_scale", 0.15)
    except Exception as error:  # property name differs between engine versions; the default look is acceptable
        unreal.log_warning("SpnNavDemoMap: could not reduce the aerial perspective: " + str(error))
    sky_light = spawn(unreal.SkyLight, unreal.Vector(0.0, 0.0, 300.0), label="SPN_SkyLight")
    sky_component = sky_light.get_component_by_class(unreal.SkyLightComponent)
    sky_component.set_mobility(unreal.ComponentMobility.MOVABLE)
    sky_component.set_editor_property("real_time_capture", True)
    # no height fog: the region is kilometres wide and fog would wash the colours out


def main():
    force = "--force" in sys.argv[1:] or os.environ.get("SPN_FORCE") == "1"
    levels = unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
    if unreal.EditorAssetLibrary.does_asset_exist(MAP_PATH):
        if not force:
            unreal.log_warning("SpnNavDemoMap: " + MAP_PATH + " exists; kept unchanged (pass --force to rebuild it)")
            return
        if not levels.load_level(MAP_PATH):
            fail("could not open " + MAP_PATH)
        actors = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
        actors.destroy_actors(actors.get_all_level_actors())
    elif not levels.new_level(MAP_PATH, False):
        fail("could not create " + MAP_PATH)

    build_lighting()
    spawn(unreal.PlayerStart, PLAYER_START_LOCATION, label="SPN_PlayerStart")
    demo_class = unreal.load_class(None, DEMO_CLASS_PATH)
    if demo_class is None:
        fail("ASpnNavDemo not found; build SupernaturalProtEditor first")
    spawn(demo_class, unreal.Vector(0.0, 0.0, 0.0), label="SPN_NavDemo")

    if not levels.save_current_level():
        fail("could not save " + MAP_PATH)
    unreal.log("SpnNavDemoMap: created " + MAP_PATH)


main()
